#!/usr/bin/env python3
"""Regenerate THIRD_PARTY_LICENSES: the license notices of the Rust crates compiled into the
package, for every platform the wheels are built for.

Build-time-only crates (proc-macros and their dependencies) aren't linked into the package and
are left out. For a crate offering MIT among its licenses, its MIT license file is used;
otherwise its own license file (e.g. Zlib for zlib-rs). Run from the repository root after
changing dependencies:

  python3 scripts/third_party_licenses.py
"""
import json
import os
import re
import subprocess
import sys

TARGETS = [  # keep in step with .github/workflows/CI.yml
    "aarch64-apple-darwin", "x86_64-apple-darwin",
    "x86_64-unknown-linux-gnu", "aarch64-unknown-linux-gnu",
    "x86_64-unknown-linux-musl", "aarch64-unknown-linux-musl",
    "x86_64-pc-windows-msvc",
]
SELF = "ont_guide_aligner"


def run(*cmd):
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout


linked = set()
for t in TARGETS:
    out = run("cargo", "tree", "-e", "normal,no-proc-macro", "--target", t,
              "--prefix", "none", "--format", "{p}")
    for line in out.splitlines():
        m = re.match(r"(\S+) v(\S+)", line)
        if m and m.group(1) != SELF:
            linked.add((m.group(1), m.group(2)))

meta = json.loads(run("cargo", "metadata", "--format-version", "1"))
pkgs = {(p["name"], p["version"]): p for p in meta["packages"]}

sections = []
for name, ver in sorted(linked):
    p = pkgs[(name, ver)]
    lic = p.get("license") or ""
    d = os.path.dirname(p["manifest_path"])
    files = sorted(os.listdir(d))
    if re.search(r"\bMIT\b", lic) and "LICENSE-MIT" in files:
        chosen, path = "MIT", os.path.join(d, "LICENSE-MIT")
    elif lic == "Zlib" and "LICENSE" in files:
        chosen, path = "Zlib", os.path.join(d, "LICENSE")
    else:
        sys.exit(f"Don't know which license file to use for {name} {ver} ({lic}); files: {files}")
    with open(path, encoding="utf-8") as f:
        text = f.read().strip()
    url = p.get("repository") or f"https://crates.io/crates/{name}"
    sections.append(f"{name} {ver}\n{url}\nLicense: {lic} (used here under {chosen})\n\n{text}\n")

header = (
    "Third-party software in ont-guide-aligner\n"
    "==========================================\n\n"
    "The compiled core of ont-guide-aligner includes the following Rust crates. Their license\n"
    "notices are reproduced below. Generated by scripts/third_party_licenses.py.\n"
)
rule = "\n" + "-" * 78 + "\n\n"
with open("THIRD_PARTY_LICENSES", "w", encoding="utf-8") as f:
    f.write(header + rule + rule.join(sections))
print(f"Wrote THIRD_PARTY_LICENSES ({len(sections)} crates)")
